"""Write the fidelity fixtures from geometries already in the tree.

Run from the repository root:

    python bench/fidelity/make_fixtures.py
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
DEST = HERE / "fixtures"
sys.path.insert(0, str(HERE))

import geom  # noqa: E402
import readcon  # noqa: E402

NEB_SRC = ROOT / "resources" / "examples" / "neb_band.con"
CONVEL_SRC = ROOT / "resources" / "test" / "tiny_multi_cuh2.convel"
FS_SRC = ROOT / "resources" / "test" / "v30_fs_label.convel"
NEB_MARK = "example NEB image 3"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _claisen_frame(rows, user):
    atoms = []
    for symbol, atom_id, pos in rows:
        atoms.append(
            readcon.Atom(
                symbol,
                float(pos[0]),
                float(pos[1]),
                float(pos[2]),
                atom_id=int(atom_id),
                mass=geom.MASS[symbol],
            )
        )
    frame = readcon.ConFrame(
        cell=[geom.CELL, geom.CELL, geom.CELL],
        angles=[90.0, 90.0, 90.0],
        atoms=atoms,
    )
    frame.metadata["comment"] = user
    return frame


def _write_claisen(path: Path) -> None:
    reactant, product = geom.claisen_rows()
    frames = [
        _claisen_frame(reactant, "Claisen reactant, allyl vinyl ether"),
        _claisen_frame(product, "Claisen product, oxygen first, C5 image"),
    ]
    readcon.write_con(str(path), frames)


def _write_slab(path: Path) -> None:
    slab = geom.slab_geometry()
    atoms = []
    for symbol, pos, mass, mask, atom_id in zip(
        slab["symbols"],
        slab["positions"],
        slab["masses"],
        slab["mask"],
        slab["ids"],
        strict=True,
    ):
        atoms.append(
            readcon.Atom(
                symbol,
                float(pos[0]),
                float(pos[1]),
                float(pos[2]),
                fixed=[bool(bit) for bit in mask],
                atom_id=int(atom_id),
                mass=float(mass),
            )
        )
    frame = readcon.ConFrame(
        cell=[float(v) for v in slab["cell"]],
        angles=[float(v) for v in slab["angles"]],
        atoms=atoms,
    )
    frame.metadata["pbc"] = slab["pbc"]
    frame.metadata["comment"] = "Pt100 2x2x2 hollow adatom, failure_matrix geometry"
    readcon.write_con(str(path), [frame])


def _write_neb(path: Path) -> None:
    text = NEB_SRC.read_text(encoding="utf-8")
    cut = text.index(NEB_MARK)
    path.write_text(text[:cut], encoding="utf-8")


def _copy(src: Path, dest: Path) -> None:
    dest.write_bytes(src.read_bytes())


def main() -> None:
    DEST.mkdir(parents=True, exist_ok=True)
    _write_claisen(DEST / "claisen.con")
    _write_neb(DEST / "neb_band_3.con")
    _write_slab(DEST / "pt100_slab.con")
    _copy(CONVEL_SRC, DEST / "tiny_multi_cuh2.convel")
    _copy(FS_SRC, DEST / "v30_fs_label.convel")
    lines = [
        "Fixtures for the fidelity head-to-head. Regenerated by",
        "bench/fidelity/make_fixtures.py.",
        "",
        "claisen.con",
        "  Two frames from tests/python/test_atom_correspondence.py.",
        "  Frame 0 is the allyl vinyl ether reactant. Frame 1 is the",
        "  4-pentenal product stored oxygen-first, with C5 one cell along +x.",
        "",
        "neb_band_3.con",
        "  First three images of resources/examples/neb_band.con, cut on the",
        "  line 'example NEB image 3' and otherwise byte for byte. The images",
        "  are the reactant, the saddle, and the descending image.",
        "",
        "pt100_slab.con",
        "  Pt(100) 2x2x2 plus a hollow adatom, the geometry of",
        "  paper/cpc/scripts/failure_matrix.py fixture(), without velocities.",
        "  The bottom four atoms are fixed on every axis. The adatom is fixed",
        "  in z only. Ids are 17, 3, 11, 5, 23, 2, 13, 7, 41. Positions include",
        "  that fixture's seed-20261014 perturbation of 1e-3 angstrom.",
        "",
        "tiny_multi_cuh2.convel",
        "  Byte copy of resources/test/tiny_multi_cuh2.convel.",
        f"  sha256 {_sha(DEST / 'tiny_multi_cuh2.convel')}",
        "",
        "v30_fs_label.convel",
        "  Byte copy of resources/test/v30_fs_label.convel.",
        "  The file names units.time fs. Spec minor 0 still stores velocities",
        "  in the natural unit; the label is not authoritative.",
        f"  sha256 {_sha(DEST / 'v30_fs_label.convel')}",
        "",
    ]
    (DEST / "PROVENANCE.txt").write_text("\n".join(lines), encoding="utf-8")
    for path in sorted(DEST.iterdir()):
        print(f"{path.name} {path.stat().st_size}")


if __name__ == "__main__":
    main()
