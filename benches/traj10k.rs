//! Single-thread read and write of a varying 10_000-frame, 218-atom trajectory.
//!
//! The coordinates shift every frame so the parser and the round-trip writer
//! cannot treat the file as one repeated block.

use criterion::{Criterion, criterion_group, criterion_main};
use readcon_core::iterators::ConFrameIterator;
use readcon_core::types::ConFrame;
use readcon_core::writer::ConFrameWriter;
use std::hint::black_box;
use std::time::Duration;

fn generate(nframes: usize) -> String {
    let mut out = String::with_capacity(nframes * 14_000);
    for f in 0..nframes {
        let shift = (f as f64) * 1.0e-4;
        out.push_str("Generated by benchmark\n");
        out.push_str("{\"con_spec_version\":2}\n");
        out.push_str("15.3456 21.702 100.0\n");
        out.push_str("90.0 90.0 90.0\n");
        out.push_str("0 0\n");
        out.push_str(&format!("{f} 0 1\n"));
        out.push_str("2\n");
        out.push_str("216 2\n");
        out.push_str("63.546 1.00793\n");
        out.push_str("Cu\nCoordinates of Component 1\n");
        for i in 0..216 {
            let x = (i % 6) as f64 * 2.557 + 0.6394 + shift;
            let y = ((i / 6) % 6) as f64 * 3.617 + 0.9045 + shift * 0.5;
            let z = (i / 36) as f64 * 2.087 + (f as f64) * 1.0e-6;
            out.push_str(&format!("   {x:.17}    {y:.17}    {z:.17} 0    {i}\n"));
        }
        out.push_str("H\nCoordinates of Component 2\n");
        let hx = 8.6823 + shift;
        let hy = 9.947;
        let hz = 11.733 + (f as f64) * 1.0e-5;
        out.push_str(&format!("   {hx:.17}    {hy:.17}    {hz:.17} 0  216\n"));
        let hx2 = 7.9421 + shift * 0.25;
        out.push_str(&format!("   {hx2:.17}    {hy:.17}    {hz:.17} 0  217\n"));
    }
    out
}

fn read_all(text: &str) -> Vec<ConFrame> {
    ConFrameIterator::new(text)
        .map(|frame| frame.expect("parse"))
        .collect()
}

fn traj10k(c: &mut Criterion) {
    let text = generate(10_000);
    let frames = read_all(&text);
    let mut group = c.benchmark_group("traj10k_218");
    group.sample_size(10);
    group.measurement_time(Duration::from_secs(6));
    group.bench_function("read", |b| {
        b.iter(|| {
            let n: usize = ConFrameIterator::new(black_box(text.as_str()))
                .map(|frame| frame.expect("parse").atom_data.len())
                .sum();
            black_box(n);
        });
    });
    let mut buf = Vec::with_capacity(text.len());
    group.bench_function("write", |b| {
        b.iter(|| {
            buf.clear();
            {
                let mut writer = ConFrameWriter::new(&mut buf);
                writer.extend(frames.iter()).expect("write");
            }
            black_box(buf.len());
        });
    });
    group.finish();
}

criterion_group!(benches, traj10k);
criterion_main!(benches);
