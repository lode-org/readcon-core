//! Read and write of a 10_000-atom frame and a 1_000-frame trajectory.
//!
//! Both use `{:.17}` coordinates, the fixed-point spelling common in dumps.
//! The 10_000-atom cell is a 50×50×4 slab, so some values sit past 100 and
//! the decimal has 20 digits. The trajectory moves every frame.

use criterion::{Criterion, criterion_group, criterion_main};
use readcon_core::iterators::ConFrameIterator;
use readcon_core::types::ConFrame;
use readcon_core::writer::ConFrameWriter;
use std::hint::black_box;
use std::time::Duration;

fn slab(n_atoms: usize, frame: usize, shift: f64) -> String {
    let mut out = String::with_capacity(n_atoms * 80 + 200);
    out.push_str("Generated by benchmark\n");
    out.push_str("{\"con_spec_version\":2}\n");
    out.push_str("180.0 180.0 40.0\n");
    out.push_str("90.0 90.0 90.0\n");
    out.push_str("0 0\n");
    out.push_str(&format!("{frame} 0 1\n"));
    out.push_str("1\n");
    out.push_str(&format!("{n_atoms}\n"));
    out.push_str("63.546\n");
    out.push_str("Cu\nCoordinates of Component 1\n");
    for i in 0..n_atoms {
        let x = (i % 50) as f64 * 3.6 + 0.6394 + shift;
        let y = ((i / 50) % 50) as f64 * 3.6 + 0.9045 + shift * 0.5;
        let z = (i / 2500) as f64 * 3.6 + (frame as f64) * 1.0e-6;
        out.push_str(&format!("   {x:.17}    {y:.17}    {z:.17} 0    {i}\n"));
    }
    out
}

fn trajectory(nframes: usize, natoms: usize) -> String {
    let mut out = String::new();
    for frame in 0..nframes {
        out.push_str(&slab(natoms, frame, frame as f64 * 1.0e-4));
    }
    out
}

fn read_atoms(text: &str) -> usize {
    ConFrameIterator::new(text)
        .map(|frame| frame.expect("parse").atom_data.len())
        .sum()
}

fn write_frames(frames: &[ConFrame], cap: usize) -> usize {
    let mut buf = Vec::with_capacity(cap);
    {
        let mut writer = ConFrameWriter::new(&mut buf);
        writer.extend(frames.iter()).expect("write");
    }
    buf.len()
}

fn parsed(text: &str) -> Vec<ConFrame> {
    ConFrameIterator::new(text)
        .map(|frame| frame.expect("parse"))
        .collect()
}

fn con_scale(c: &mut Criterion) {
    let one = slab(10_000, 0, 0.0);
    let traj = trajectory(1_000, 64);
    let small = trajectory(1_000, 2);
    let one_frames = parsed(&one);
    let traj_frames = parsed(&traj);
    let small_frames = parsed(&small);

    let mut group = c.benchmark_group("con_scale");
    group.sample_size(10);
    group.measurement_time(Duration::from_secs(4));

    group.bench_function("read_10k_atoms", |b| {
        b.iter(|| black_box(read_atoms(black_box(&one))))
    });
    group.bench_function("write_10k_atoms", |b| {
        b.iter(|| black_box(write_frames(&one_frames, one.len())))
    });
    group.bench_function("read_1000x64", |b| {
        b.iter(|| black_box(read_atoms(black_box(&traj))))
    });
    group.bench_function("write_1000x64", |b| {
        b.iter(|| black_box(write_frames(&traj_frames, traj.len())))
    });
    group.bench_function("read_1000x2", |b| {
        b.iter(|| black_box(read_atoms(black_box(&small))))
    });
    group.bench_function("write_1000x2", |b| {
        b.iter(|| black_box(write_frames(&small_frames, small.len())))
    });
    group.finish();
}

criterion_group!(benches, con_scale);
criterion_main!(benches);
