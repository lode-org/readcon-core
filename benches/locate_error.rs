//! Cost of opt-in error locations on a 3552-atom, 200-frame trajectory
//! with a declared forces section.
//!
//! `valid/*` times a clean read through `next` and `next_located`.
//! `bad_last/*` puts an invalid float on the final atom row of the last
//! frame, so each case reads the whole file before it fails.

use criterion::{Criterion, criterion_group, criterion_main};
use readcon_core::iterators::{ConFrameIterator, locate_first_error};
use std::fmt::Write;
use std::hint::black_box;
use std::time::Duration;

const TYPES: [(&str, f64, usize); 3] = [("Pt", 195.084, 3456), ("O", 15.999, 32), ("H", 1.008, 64)];
const NFRAMES: usize = 200;

fn generate(nframes: usize) -> String {
    let natoms: usize = TYPES.iter().map(|t| t.2).sum();
    let mut out = String::with_capacity(nframes * natoms * 90);
    for f in 0..nframes {
        let shift = f as f64 * 1.0e-4;
        out.push_str("Generated by benchmark\n");
        out.push_str("{\"con_spec_version\":3,\"con_spec_minor\":1,\"units\":{\"length\":\"angstrom\",\"energy\":\"eV\"},\"sections\":[\"forces\"]}\n");
        out.push_str("33.6 33.6 60.0\n90.0 90.0 90.0\n0 0\n");
        writeln!(out, "{f} 0 1").unwrap();
        writeln!(out, "{}", TYPES.len()).unwrap();
        let counts: Vec<String> = TYPES.iter().map(|t| t.2.to_string()).collect();
        writeln!(out, "{}", counts.join(" ")).unwrap();
        let masses: Vec<String> = TYPES.iter().map(|t| t.1.to_string()).collect();
        writeln!(out, "{}", masses.join(" ")).unwrap();
        for block in ["Coordinates", "Forces"] {
            if block == "Forces" {
                out.push('\n');
            }
            let mut id = 0usize;
            for (k, (sym, _, n)) in TYPES.iter().enumerate() {
                writeln!(out, "{sym}\n{block} of Component {}", k + 1).unwrap();
                for i in 0..*n {
                    let x = (i % 12) as f64 * 2.8 + 0.123456789 + shift;
                    let y = ((i / 12) % 12) as f64 * 2.8 + 0.987654321 + shift * 0.5;
                    let z = (i / 144) as f64 * 2.3 + 0.5 + f as f64 * 1.0e-6;
                    let fixed = if *sym == "Pt" && i < 1152 { 7 } else { 0 };
                    let (a, b, c) = if block == "Forces" {
                        (x * 1.0e-3, -y * 1.0e-3, z * 1.0e-3)
                    } else {
                        (x, y, z)
                    };
                    writeln!(out, "{a:.17} {b:.17} {c:.17} {fixed} {id}").unwrap();
                    id += 1;
                }
            }
        }
    }
    out
}

/// The same text with the last coordinate row of the last frame broken.
fn break_last_frame(text: &str) -> String {
    let last = text.rfind("Generated by benchmark\n").expect("frame");
    let forces = last + text[last..].find("\n\n").expect("forces block");
    let row = text[..forces].rfind('\n').expect("row") + 1;
    let mut out = text.to_string();
    out.replace_range(row..row + 1, "x");
    out
}

fn read_next(text: &str) -> Result<usize, String> {
    let mut atoms = 0;
    for frame in ConFrameIterator::new(text) {
        atoms += frame.map_err(|e| e.to_string())?.atom_data.len();
    }
    Ok(atoms)
}

fn read_next_located(text: &str) -> Result<usize, String> {
    let mut atoms = 0;
    let mut iter = ConFrameIterator::new(text);
    while let Some(frame) = iter.next_located() {
        atoms += frame.map_err(|e| e.to_string())?.atom_data.len();
    }
    Ok(atoms)
}

fn locate(c: &mut Criterion) {
    let valid = generate(NFRAMES);
    let bad = break_last_frame(&valid);
    assert_eq!(read_next(&valid), read_next_located(&valid));
    assert!(read_next(&bad).is_err());
    let err = locate_first_error(bad.as_bytes()).expect("an error");
    assert_eq!(err.location.frame, NFRAMES - 1);
    eprintln!(
        "locate_error: {} bytes, {} lines, error at {err}",
        valid.len(),
        valid.lines().count()
    );

    let mut group = c.benchmark_group("locate_3552x200");
    group.sample_size(20);
    group.measurement_time(Duration::from_secs(10));
    group.bench_function("valid/next", |b| {
        b.iter(|| black_box(read_next(black_box(&valid))))
    });
    group.bench_function("valid/next_located", |b| {
        b.iter(|| black_box(read_next_located(black_box(&valid))))
    });
    group.bench_function("bad_last/next", |b| {
        b.iter(|| black_box(read_next(black_box(&bad))))
    });
    group.bench_function("bad_last/next_located", |b| {
        b.iter(|| black_box(read_next_located(black_box(&bad))))
    });
    group.bench_function("bad_last/locate_first_error", |b| {
        b.iter(|| black_box(locate_first_error(black_box(bad.as_bytes()))))
    });
    group.finish();
}

criterion_group!(benches, locate);
criterion_main!(benches);
