//! Chemfiles XYZ read/write of the same varying 10_000 × 218 trajectory the
//! criterion bench uses. Build with `--features chemfiles-from-sources`.
//!
//! ```text
//! cargo +1.90.0 run --release --features chemfiles-from-sources --example chemfiles_xyz_time
//! ```

use chemfiles::{Atom, Frame, Trajectory};
use readcon_core::iterators::{ConFrameIterator, read_all_frames};
use readcon_core::writer::ConFrameWriter;
use std::path::Path;
use std::time::Instant;

fn main() {
    let nframes = std::env::args()
        .nth(1)
        .and_then(|s| s.parse().ok())
        .unwrap_or(10_000usize);
    let dir = std::env::temp_dir();
    let con_path = dir.join("readcon-traj10k.con");
    let xyz_path = dir.join("readcon-traj10k.xyz");
    let con = generate_con(nframes);
    let xyz = generate_xyz(nframes);
    std::fs::write(&con_path, con.as_bytes()).unwrap();
    std::fs::write(&xyz_path, xyz.as_bytes()).unwrap();
    eprintln!(
        "con {:.1} MiB  xyz {:.1} MiB",
        con.len() as f64 / (1024.0 * 1024.0),
        xyz.len() as f64 / (1024.0 * 1024.0)
    );

    let t = Instant::now();
    let frames = read_all_frames(&con_path).unwrap();
    eprintln!(
        "readcon file read {} frames in {:.3} s",
        frames.len(),
        t.elapsed().as_secs_f64()
    );

    let t = Instant::now();
    let n: usize = ConFrameIterator::new(&con)
        .map(|frame| frame.expect("parse").atom_data.len())
        .sum();
    eprintln!(
        "readcon memory read {n} atoms in {:.3} s",
        t.elapsed().as_secs_f64()
    );

    let t = Instant::now();
    let mut buf = Vec::with_capacity(con.len());
    {
        let mut writer = ConFrameWriter::new(&mut buf);
        writer.extend(frames.iter()).unwrap();
    }
    eprintln!(
        "readcon write {} bytes in {:.3} s",
        buf.len(),
        t.elapsed().as_secs_f64()
    );

    time_chemfiles_read(&xyz_path, nframes);
    time_chemfiles_write(&xyz_path, nframes);
}

fn time_chemfiles_read(path: &Path, expect: usize) {
    let t = Instant::now();
    let mut traj = Trajectory::open(path, 'r').unwrap();
    let mut frame = Frame::new();
    let mut atoms = 0usize;
    for _ in 0..expect {
        traj.read(&mut frame).expect("xyz frame");
        atoms += frame.size();
    }
    let n = expect;
    eprintln!(
        "chemfiles xyz read {n} frames ({atoms} atoms) in {:.3} s",
        t.elapsed().as_secs_f64()
    );
}

fn time_chemfiles_write(path: &Path, nframes: usize) {
    let out = path.with_file_name("readcon-traj10k-out.xyz");
    let cu = Atom::new("Cu");
    let h = Atom::new("H");
    let t = Instant::now();
    let mut traj = Trajectory::open(&out, 'w').unwrap();
    for f in 0..nframes {
        let mut frame = Frame::new();
        let shift = f as f64 * 1.0e-4;
        for i in 0..216 {
            let x = (i % 6) as f64 * 2.557 + 0.6394 + shift;
            let y = ((i / 6) % 6) as f64 * 3.617 + 0.9045 + shift * 0.5;
            let z = (i / 36) as f64 * 2.087 + (f as f64) * 1.0e-6;
            frame.add_atom(&cu, [x, y, z], None);
        }
        let hx = 8.6823 + shift;
        let hy = 9.947;
        let hz = 11.733 + (f as f64) * 1.0e-5;
        frame.add_atom(&h, [hx, hy, hz], None);
        frame.add_atom(&h, [7.9421 + shift * 0.25, hy, hz], None);
        traj.write(&frame).unwrap();
    }
    drop(traj);
    eprintln!(
        "chemfiles xyz write {} frames in {:.3} s",
        nframes,
        t.elapsed().as_secs_f64()
    );
}

fn generate_con(nframes: usize) -> String {
    let mut out = String::with_capacity(nframes * 14_000);
    for f in 0..nframes {
        let shift = (f as f64) * 1.0e-4;
        out.push_str("Generated by benchmark\n");
        out.push_str("{\"con_spec_version\":2}\n");
        out.push_str("15.3456 21.702 100.0\n");
        out.push_str("90.0 90.0 90.0\n");
        out.push_str("0 0\n");
        out.push_str(&format!("{f} 0 1\n"));
        out.push_str("2\n216 2\n63.546 1.00793\n");
        out.push_str("Cu\nCoordinates of Component 1\n");
        for i in 0..216 {
            let x = (i % 6) as f64 * 2.557 + 0.6394 + shift;
            let y = ((i / 6) % 6) as f64 * 3.617 + 0.9045 + shift * 0.5;
            let z = (i / 36) as f64 * 2.087 + (f as f64) * 1.0e-6;
            out.push_str(&format!("   {x:.17}    {y:.17}    {z:.17} 0    {i}\n"));
        }
        out.push_str("H\nCoordinates of Component 2\n");
        let hz = 11.733 + (f as f64) * 1.0e-5;
        out.push_str(&format!(
            "   {:.17}    {:.17}    {:.17} 0  216\n   {:.17}    {:.17}    {:.17} 0  217\n",
            8.6823 + shift,
            9.947,
            hz,
            7.9421 + shift * 0.25,
            9.947,
            hz
        ));
    }
    out
}

fn generate_xyz(nframes: usize) -> String {
    let mut out = String::with_capacity(nframes * 12_000);
    for f in 0..nframes {
        let shift = (f as f64) * 1.0e-4;
        out.push_str("218\n");
        out.push_str(&format!("frame {f}\n"));
        for i in 0..216 {
            let x = (i % 6) as f64 * 2.557 + 0.6394 + shift;
            let y = ((i / 6) % 6) as f64 * 3.617 + 0.9045 + shift * 0.5;
            let z = (i / 36) as f64 * 2.087 + (f as f64) * 1.0e-6;
            out.push_str(&format!("Cu {x:.17} {y:.17} {z:.17}\n"));
        }
        let hz = 11.733 + (f as f64) * 1.0e-5;
        out.push_str(&format!(
            "H {:.17} {:.17} {:.17}\nH {:.17} {:.17} {:.17}\n",
            8.6823 + shift,
            9.947,
            hz,
            7.9421 + shift * 0.25,
            9.947,
            hz
        ));
    }
    out
}
