#[test]
fn round_trip_is_the_writer_default_and_lattice_lines_follow_vectors() {
    assert_eq!(FloatFormat::default(), FloatFormat::RoundTrip);
    let vecs = [[2.0, 0.0, 0.0], [0.5, 3.0, 0.0], [0.0, 0.0, 4.0]];
    let (boxl, angles) = lengths_and_angles(vecs);
    let mut builder = ConFrameBuilder::new([10.0; 3], [90.0; 3]);
    builder.add_atom("H", 1.25, 0.0, 0.0, [false; 3], 3, 1.0);
    let mut frame = builder.build().unwrap();
    frame.header.set_lattice_vectors(vecs);
    assert_eq!(frame.header.boxl, boxl);
    assert_eq!(frame.header.angles, angles);
    let mut buf = Vec::new();
    ConFrameWriter::new(&mut buf).write_frame(&frame).unwrap();
    let text = String::from_utf8(buf).unwrap();
    let parsed = parse_one(&text).unwrap();
    assert_eq!(parsed.atom_data[0].x.to_bits(), 1.25_f64.to_bits());
    assert!((parsed.header.boxl[0] - 2.0).abs() < 1e-12);
    assert!((parsed.header.boxl[1] - (0.5_f64 * 0.5 + 9.0).sqrt()).abs() < 1e-9);
    assert!((parsed.header.boxl[2] - 4.0).abs() < 1e-12);
}

