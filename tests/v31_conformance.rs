#[test]
fn m4_atom_id_is_not_parsed_as_float() {
    let id = "9007199254740993";
    let text = v2_frame(r#"{"con_spec_version":2}"#, &format!("1.0 2.0 3.0 0 {id}"));
    let frame = parse_one(&text).unwrap();
    assert_eq!(frame.atom_data[0].atom_id, 9_007_199_254_740_993);

    let decimal = v2_frame(r#"{"con_spec_version":2}"#, "1.0 2.0 3.0 0 1.5");
    assert_eq!(class_of(&decimal), "InvalidNumberFormat");
    let negative = v2_frame(r#"{"con_spec_version":2}"#, "1.0 2.0 3.0 0 -1");
    assert_eq!(class_of(&negative), "InvalidNumberFormat");

    let missing = v2_frame(r#"{"con_spec_version":2}"#, "1.0 2.0 3.0 0");
    let frame = parse_one(&missing).unwrap();
    assert_eq!(frame.atom_data[0].atom_id, 0);
}

