/// CON-compress.1.
#[test]
fn m10_gzip_reads_every_member() {
    let one = v2_frame(r#"{"con_spec_version":2}"#, "1.0 0.0 0.0 0 0");
    let two = v2_frame(r#"{"con_spec_version":2}"#, "2.0 0.0 0.0 0 1");
    let member = |text: &str| -> Vec<u8> {
        let mut enc = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
        std::io::Write::write_all(&mut enc, text.as_bytes()).unwrap();
        enc.finish().unwrap()
    };
    let mut bytes = member(&one);
    bytes.extend(member(&two));
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("two.con.gz");
    std::fs::write(&path, &bytes).unwrap();
    let frames = readcon_core::iterators::read_all_frames(&path).unwrap();
    assert_eq!(frames.len(), 2);
    assert_eq!(frames[0].atom_data[0].x, 1.0);
    assert_eq!(frames[1].atom_data[0].x, 2.0);
}

