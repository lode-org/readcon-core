//! v3.1 reader and writer conformance. One case per M-item that the
//! hand parser owns (M8 and M9 are the ASE adapters). Clause ids are
//! the ones in docs/orgmode/clauses.tsv on the spec branch.

use readcon_core::error::ParseError;
use readcon_core::iterators::ConFrameIterator;
#[cfg(feature = "parallel")]
use readcon_core::iterators::{frame_start_offsets, frames_from_text};
use readcon_core::types::{ConFrame, ConFrameBuilder, lengths_and_angles};
use readcon_core::units::NATURAL_TIME_UNIT;
use readcon_core::writer::{ConFrameWriter, FloatFormat};
#[cfg(feature = "parallel")]
use std::hash::{Hash, Hasher};

fn class_of(text: &str) -> String {
    match ConFrameIterator::new(text).next() {
        Some(Err(err)) => err.class_name().to_string(),
        Some(Ok(_)) => "ok".into(),
        None => "empty".into(),
    }
}

fn parse_one(text: &str) -> Result<ConFrame, ParseError> {
    match ConFrameIterator::new(text).next() {
        Some(result) => result,
        None => panic!("no frame"),
    }
}

fn v2_frame(meta: &str, body: &str) -> String {
    format!(
        "PRE\n{meta}\n10.0 20.0 30.0\n90.0 90.0 90.0\nPOST1\nPOST2\n1\n1\n12.011\nC\nCoordinates of Component 1\n{body}\n"
    )
}

fn header_only(line2: &str, counts: &str) -> String {
    format!("PRE\n{line2}\n10.0 20.0 30.0\n90.0 90.0 90.0\nPOST1\nPOST2\n{counts}")
}

#[test]
fn m1_non_finite_rejected_without_validate() {
    for token in ["NaN", "nan", "+NaN", "-inf", "INF", "Infinity", "+infinity"] {
        let cell = header_only(r#"{"con_spec_version":2}"#, &format!("1\n1\n1.0\n"));
        let text = format!(
            "PRE\n{{\"con_spec_version\":2}}\n10.0 {token} 30.0\n90 90 90\nA\nB\n1\n1\n1.0\n"
        );
        let err = parse_one(&text).unwrap_err();
        assert_eq!(err.class_name(), "NonFiniteValue", "{token} in {cell}");
        assert!(
            err.to_string().to_ascii_lowercase().contains("nan")
                || err.to_string().to_ascii_lowercase().contains("inf"),
            "{err}"
        );
    }
    let coord = v2_frame(r#"{"con_spec_version":2}"#, "1.0 nan 0.0 0 0");
    assert_eq!(class_of(&coord), "NonFiniteValue");
}

#[test]
fn m2_column_four_is_an_integer_token() {
    let flagged = v2_frame(r#"{"con_spec_version":2}"#, "0.0 0.0 0.0 0.0 1");
    let err = parse_one(&flagged).unwrap_err();
    assert_eq!(err.class_name(), "InvalidFixedFlag");
    assert!(err.to_string().contains("0.0"));

    let eight = v2_frame(r#"{"con_spec_version":2}"#, "0.0 0.0 0.0 8 1");
    assert_eq!(class_of(&eight), "InvalidFixedFlag");

    let signed = v2_frame(r#"{"con_spec_version":2}"#, "0.0 0.0 0.0 -1 1");
    assert_eq!(class_of(&signed), "InvalidFixedFlag");

    let x_only = parse_one(&v2_frame(r#"{"con_spec_version":2}"#, "1.0 2.0 3.0 1 4")).unwrap();
    assert_eq!(x_only.atom_data[0].fixed, [true, false, false]);

    let legacy = "\
PRE
free text
10 10 10
90 90 90
A
B
1
1
12.0
H
Coordinates of Component 1
1.0 2.0 3.0 1 0
";
    let frame = parse_one(legacy).unwrap();
    assert_eq!(frame.header.spec_version, 1);
    assert_eq!(frame.atom_data[0].fixed, [true, true, true]);
}

