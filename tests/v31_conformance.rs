#[test]
fn v31_writer_requires_time_when_velocities_are_present() {
    let mut builder = ConFrameBuilder::new([10.0; 3], [90.0; 3]);
    builder
        .add_atom("H", 0.0, 0.0, 0.0, [false; 3], 0, 1.0)
        .with_velocity([0.1, 0.0, 0.0]);
    let frame = builder.build().unwrap();
    let mut buf = Vec::new();
    let err = ConFrameWriter::new(&mut buf)
        .write_frame(&frame)
        .unwrap_err();
    match err {
        readcon_core::writer::WriteError::Format(ParseError::InvalidUnits(_)) => {}
        other => panic!("{other}"),
    }
    let mut units = frame.header.units().cloned().unwrap();
    units["time"] = serde_json::json!(NATURAL_TIME_UNIT);
    let mut stamped = frame;
    stamped.header.set_units(units);
    let mut buf = Vec::new();
    ConFrameWriter::new(&mut buf).write_frame(&stamped).unwrap();
    let text = String::from_utf8(buf).unwrap();
    assert!(text.contains(NATURAL_TIME_UNIT), "{text}");
    assert!(!text.contains("\"time\":\"fs\"") && !text.contains("\"time\": \"fs\""));
}

fn natural_time_golden() -> Vec<u8> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("resources/conformance/natural_time_unit.txt");
    std::fs::read(path).unwrap()
}

fn assert_written_time_is_golden(bytes: &[u8], golden: &[u8]) {
    assert!(
        bytes.windows(golden.len()).any(|window| window == golden),
        "missing pinned spelling in {}",
        String::from_utf8_lossy(bytes)
    );
    let spaced = b"(amu * angstrom^2 / eV) ^0.5";
    assert!(
        !bytes.windows(spaced.len()).any(|window| window == spaced),
        "spaced spelling leaked into {}",
        String::from_utf8_lossy(bytes)
    );
}

fn velocity_frame() -> ConFrameBuilder {
    let mut builder = ConFrameBuilder::new([10.0; 3], [90.0; 3]);
    builder
        .add_atom("H", 0.0, 0.0, 0.0, [false; 3], 0, 1.0)
        .with_velocity([0.1, 0.0, 0.0]);
    builder
}

#[test]
fn natural_time_spelling_is_byte_exact_on_write() {
    let golden = natural_time_golden();
    assert_eq!(golden, NATURAL_TIME_UNIT.as_bytes());
    let spaced = "( amu * angstrom ^ 2 / eV ) ^ 0.5";

    let mut via_set_units = velocity_frame();
    via_set_units
        .set_units(serde_json::json!({
            "length": "angstrom",
            "energy": "eV",
            "mass": "amu",
            "time": spaced
        }))
        .unwrap();
    let mut buf = Vec::new();
    ConFrameWriter::new(&mut buf)
        .write_frame(&via_set_units.build().unwrap())
        .unwrap();
    assert_written_time_is_golden(&buf, &golden);

    let mut via_metadata = velocity_frame();
    via_metadata
        .set_metadata_json(&format!(
            r#"{{"units":{{"length":"angstrom","energy":"eV","mass":"amu","time":"{spaced}"}}}}"#
        ))
        .unwrap();
    buf.clear();
    ConFrameWriter::new(&mut buf)
        .write_frame(&via_metadata.build().unwrap())
        .unwrap();
    assert_written_time_is_golden(&buf, &golden);

    // from_ase stores this object and the writer canonicalises it.
    let mut via_from_ase = velocity_frame();
    let mut meta = std::collections::BTreeMap::new();
    meta.insert(
        "units".into(),
        serde_json::json!({
            "length": "angstrom",
            "energy": "eV",
            "mass": "amu",
            "time": spaced
        }),
    );
    meta.insert(
        "con_spec_minor".into(),
        serde_json::json!(readcon_core::CON_SPEC_MINOR),
    );
    via_from_ase.metadata(meta);
    buf.clear();
    ConFrameWriter::new(&mut buf)
        .write_frame(&via_from_ase.build().unwrap())
        .unwrap();
    assert_written_time_is_golden(&buf, &golden);
}

#[cfg(feature = "parallel")]
fn digest(frames: &[ConFrame]) -> u64 {
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    frames.len().hash(&mut hasher);
    for frame in frames {
        frame.header.spec_version.hash(&mut hasher);
        frame.header.natm_types.hash(&mut hasher);
        frame.header.natms_per_type.hash(&mut hasher);
        frame.header.sections.hash(&mut hasher);
        for value in frame.header.boxl {
            value.to_bits().hash(&mut hasher);
        }
        for value in frame.header.angles {
            value.to_bits().hash(&mut hasher);
        }
        for mass in &frame.header.masses_per_type {
            mass.to_bits().hash(&mut hasher);
        }
        format!("{:?}", frame.header.metadata).hash(&mut hasher);
        for atom in &frame.atom_data {
            atom.symbol.hash(&mut hasher);
            atom.x.to_bits().hash(&mut hasher);
            atom.y.to_bits().hash(&mut hasher);
            atom.z.to_bits().hash(&mut hasher);
            atom.fixed.hash(&mut hasher);
            atom.atom_id.hash(&mut hasher);
            atom.velocity.map(|v| v.map(f64::to_bits)).hash(&mut hasher);
            atom.force.map(|v| v.map(f64::to_bits)).hash(&mut hasher);
            atom.energy.map(f64::to_bits).hash(&mut hasher);
            atom.charge.map(f64::to_bits).hash(&mut hasher);
            atom.spin.map(f64::to_bits).hash(&mut hasher);
            atom.magmom.map(|v| v.map(f64::to_bits)).hash(&mut hasher);
            atom.displacement
                .map(|v| v.map(f64::to_bits))
                .hash(&mut hasher);
            atom.spread.map(|v| v.map(f64::to_bits)).hash(&mut hasher);
        }
    }
    hasher.finish()
}

#[cfg(feature = "parallel")]
#[test]
fn thread_counts_hash_every_field_and_share_the_first_error() {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("resources/test/cuh2.con");
    let one = std::fs::read_to_string(&path).unwrap();
    let text = one.repeat(4);
    let offsets = frame_start_offsets(&text);
    assert_eq!(offsets.len(), 4);
    let sequential = frames_from_text(&text, Some(1)).unwrap();
    let base = digest(&sequential);
    for threads in [1usize, 2, 3, 8] {
        let frames = frames_from_text(&text, Some(threads)).unwrap();
        assert_eq!(digest(&frames), base, "threads {threads}");
        assert_eq!(frames, sequential);
    }
    let bad = format!(
        "{text}{}",
        v2_frame(r#"{"con_spec_version":2}"#, "nan 0 0 0 0")
    );
    let mut first = None;
    for threads in [1usize, 2, 3, 8] {
        let err = frames_from_text(&bad, Some(threads)).unwrap_err();
        let stamp = (err.class_name().to_string(), err.to_string());
        match &first {
            None => first = Some(stamp),
            Some(prev) => assert_eq!(prev, &stamp, "threads {threads}"),
        }
    }
    assert_eq!(first.unwrap().0, "NonFiniteValue");
}
