#!/usr/bin/env python3
"""Write CPC table fragments from committed artifacts. Org never types the numbers."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parents[1] / "src" / "figures" / "generated"

HEADER = "% Auto-generated by paper/cpc/scripts/gen_tables.py -- do not edit by hand.\n"


def _load(path: Path) -> dict:
    return json.loads(path.read_text())


def _write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER + body)


def _ms(v: float, nd: int = 3) -> str:
    return f"${v:.{nd}f}$"


def _int_tex(n: int) -> str:
    return "$" + f"{n:,}".replace(",", r"\,") + "$"


def _bytes_tex(n: int) -> str:
    return _int_tex(n)


def gen_macros(traj: dict, h5: dict, wall_scale: dict, cmp: dict) -> str:
    frame = int(h5["con_size_bytes"]) // int(traj["n_frames"])
    seq = float(wall_scale["sequential_ms"])
    auto = float(wall_scale["auto_ms"])
    speedup = seq / auto
    return r"""
\newcommand{\conFrameBytes}{%s}
\newcommand{\conConcatBytes}{%s}
\newcommand{\wallNativeMs}{%.3f}
\newcommand{\ioSeqMs}{%.3f}
\newcommand{\ioAutoMs}{%.3f}
\newcommand{\ioSpeedup}{%.1f}
\newcommand{\wallCommit}{%s}
\newcommand{\ioCommit}{%s}
\newcommand{\ioHost}{%s}
\newcommand{\ioNcpus}{%s}
""" % (
        _bytes_tex(frame).strip("$"),
        _bytes_tex(int(h5["con_size_bytes"])).strip("$"),
        float(traj["readcon_con_median_ms"]),
        seq,
        auto,
        speedup,
        traj["commit"],
        wall_scale["commit"],
        wall_scale["host"],
        wall_scale["ncpus"],
    )


def gen_cachegrind() -> str:
    rst = (ROOT / "docs/source/_generated/cachegrind_results.rst").read_text()
    rows = {
        "parse_multi_2x4": (50, None),
        "parse_cuh2_218": (20, None),
        "parse_100_frames": (10, None),
        "forward_100_frames": (10, None),
        "write_100_frames": (10, None),
        "chemfiles_xyz_path": (50, None),
        "float_fast_float2": (r"$10^{4}$ fields", None),
        "float_std_parse": (r"$10^{4}$ fields", None),
    }
    for m in re.finditer(
        r"``([a-z0-9_]+)``\s*\n\s*-\s*([0-9,]+)", rst
    ):
        name, raw = m.group(1), m.group(2)
        if name in rows:
            repeats, _ = rows[name]
            rows[name] = (repeats, int(raw.replace(",", "")))
    missing = [k for k, v in rows.items() if v[1] is None]
    if missing:
        raise SystemExit(f"cachegrind rst missing rows: {missing}")
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        r"\caption{Cachegrind instruction counts (I-refs). Lower is better on",
        r"the same CI image. Source:",
        r"\texttt{docs/source/\_generated/cachegrind\_results.rst}.",
        r"\texttt{write\_100\_frames} is \texttt{ConFrameWriter::extend} into",
        r"a \texttt{Vec<u8>} on $100$ copies of \texttt{tiny\_cuh2.con}.",
        r"There is no Rayon scenario.}",
        r"\label{tab:cachegrind}",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Scenario & I-refs & Repeats \\",
        r"\midrule",
    ]
    order = [
        "parse_multi_2x4",
        "parse_cuh2_218",
        "parse_100_frames",
        "forward_100_frames",
        "write_100_frames",
        "chemfiles_xyz_path",
        "float_fast_float2",
        "float_std_parse",
    ]
    for name in order:
        repeats, n = rows[name]
        rep = repeats if isinstance(repeats, str) else str(repeats)
        tex_name = name.replace("_", r"\_")
        body.append(rf"\texttt{{{tex_name}}} & {_int_tex(n)} & {rep} \\")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


