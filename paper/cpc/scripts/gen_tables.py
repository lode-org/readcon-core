#!/usr/bin/env python3
"""Write CPC table fragments from committed CSVs. Org never types the numbers."""

from __future__ import annotations

import csv
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CPC = Path(__file__).resolve().parents[1]
OUT = CPC / "src" / "figures" / "generated"
DATA = CPC / "data"
RESULTS = CPC / "bench" / "results"
CLAUSES = ROOT / "docs" / "orgmode" / "clauses.tsv"
MANIFEST = ROOT / "resources" / "conformance" / "manifest.toml"
NEB = ROOT / "resources" / "examples" / "neb_band.con"
HEADER = "% Auto-generated by paper/cpc/scripts/gen_tables.py -- do not edit by hand.\n"


def tex(text: str) -> str:
    return (
        text.replace("\\", r"\textbackslash{}")
        .replace("&", r"\&")
        .replace("%", r"\%")
        .replace("_", r"\_")
        .replace("#", r"\#")
        .replace("$", r"\$")
        .replace("^", r"\^{}")
    )


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as handle:
        return list(csv.DictReader(handle))


def write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER + body)


def require(path: Path) -> None:
    if not path.is_file():
        raise SystemExit(
            f"missing {path}. Run paper/cpc/bench/run_bench.py and analyze_bench.py."
        )


def clause_rows() -> list[dict[str, str]]:
    counts: dict[str, int] = {}
    for line in CLAUSES.read_text().splitlines()[1:]:
        keyword = line.split("\t")[1]
        counts[keyword] = counts.get(keyword, 0) + 1
    rows = [{"keyword": key, "n": str(counts[key])} for key in sorted(counts)]
    path = DATA / "clause_counts.csv"
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["keyword", "n"])
        writer.writeheader()
        writer.writerows(rows)
    return rows


def phase_rows() -> list[dict[str, str]]:
    text = MANIFEST.read_text()
    blocks = re.split(r"\n(?=\[\[)", text)
    rows = []
    for block in blocks:
        if not block.startswith("[["):
            continue
        kind = "valid" if block.startswith("[[valid]]") else "invalid"
        fields = dict(re.findall(r'^(\w+)\s*=\s*"(.*)"', block, re.MULTILINE))
        rows.append(
            {
                "kind": kind,
                "id": fields.get("id", ""),
                "clause": fields.get("clause", ""),
                "error": fields.get("error", ""),
            }
        )
    path = DATA / "phase_a.csv"
    with path.open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["kind", "id", "clause", "error"])
        writer.writeheader()
        writer.writerows(rows)
    return rows


def gen_clauses(rows: list[dict[str, str]]) -> str:
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        (
            r"\caption{Clause index of CON specification 3.1. "
            r"Source: \texttt{docs/orgmode/clauses.tsv}, copied to "
            r"\texttt{paper/cpc/data/clause\_counts.csv}.}"
        ),
        r"\label{tab:clauses}",
        r"\begin{tabular}{lr}",
        r"\toprule",
        r"Keyword & Count \\",
        r"\midrule",
    ]
    for row in rows:
        body.append(rf"{tex(row['keyword'])} & {row['n']} \\")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_phase(rows: list[dict[str, str]]) -> str:
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        (
            r"\caption{Phase A corpus on this tree. "
            r"Source: \texttt{resources/conformance/manifest.toml}, copied to "
            r"\texttt{paper/cpc/data/phase\_a.csv}. "
            r"This corpus is not the v3.1 T1 set.}"
        ),
        r"\label{tab:phase-a}",
        r"\begin{tabular}{ll}",
        r"\toprule",
        r"Id & Recorded error \\",
        r"\midrule",
    ]
    for row in rows:
        err = row["error"] if row["error"] else row["kind"]
        body.append(rf"\texttt{{{tex(row['id'])}}} & {tex(err)} \\")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_features(rows: list[dict[str, str]]) -> str:
    main = [
        "readcon-core 0.16.2",
        "ASE eon.py 3.29.0",
        "extXYZ",
        "H5MD",
        "LAMMPS dump",
        "chemfiles",
    ]
    extra = ["OVITO 3.15.4", "Atomsk manual"]
    features = []
    for row in rows:
        if row["feature"] not in features:
            features.append(row["feature"])
    grid = {(r["feature"], r["reader"]): r["code"] for r in rows}

    def table(readers: list[str], label: str, caption: str) -> str:
        header = " & ".join(tex(r) for r in readers)
        lines = [
            r"\begin{table}[ht]",
            r"\centering",
            r"\scriptsize",
            rf"\caption{{{caption}}}",
            rf"\label{{{label}}}",
            r"\begin{tabular}{l" + "c" * len(readers) + "}",
            r"\toprule",
            "Feature & " + header + r" \\",
            r"\midrule",
        ]
        for feature in features:
            cells = " & ".join(tex(grid[(feature, reader)]) for reader in readers)
            lines.append(rf"{tex(feature)} & {cells} \\")
        lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
        return "\n".join(lines)

    main_tex = table(
        main,
        "tab:features",
        "Feature codes for readcon-core 0.16.2 and five other formats. "
        "Each cell is sourced in Table~\\ref{tab:feature-sources} and in "
        "\\texttt{paper/cpc/data/features.csv}.",
    )
    extra_tex = table(
        ["readcon-core 0.16.2", *extra],
        "tab:features-other",
        "OVITO and Atomsk have no CON reader in the manuals cited in "
        "Table~\\ref{tab:feature-sources}.",
    )
    sources = [
        r"\begin{longtable}{p{0.18\textwidth}p{0.22\textwidth}p{0.50\textwidth}}",
        (
            r"\caption{Source of each comparison cell. "
            r"The same rows are \texttt{paper/cpc/data/features.csv}.}"
        ),
        r"\label{tab:feature-sources}\\",
        r"\toprule",
        r"Feature & Reader & Source \\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Feature & Reader & Source \\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endfoot",
    ]
    for row in rows:
        sources.append(
            rf"{tex(row['feature'])} & {tex(row['reader'])} & {tex(row['source'])} \\"
        )
    sources += [r"\bottomrule", r"\end{longtable}", ""]
    return main_tex + "\n" + extra_tex + "\n" + "\n".join(sources)


def gen_ratios(rows: list[dict[str, str]]) -> str:
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        r"\scriptsize",
        (
            r"\caption{Paired ratios on this host. "
            r"The ratio is readcon-core time divided by the peer time. "
            r"The interval is a BCa 95 percent interval of the median. "
            r"Timeouts and reader failures are counts, not times. "
            r"Source: \texttt{paper/cpc/bench/results/ratios.csv}.}"
        ),
        r"\label{tab:ratios}",
        r"\begin{tabular}{llrrrrr}",
        r"\toprule",
        r"Payload & Peer & OK & Fail & Timeout & Ratio & BCa interval \\",
        r"\midrule",
    ]
    for row in rows:
        if row["bca_low"]:
            interval = f"[{row['bca_low']}, {row['bca_high']}]"
            ratio = row["median_ratio_readcon_over_peer"]
        else:
            interval = ""
            ratio = ""
        body.append(
            rf"{tex(row['payload'])} & {tex(row['peer'])} & {row['n_pair_ok']} & "
            rf"{row['n_failure']} & {row['n_timeout']} & {tex(ratio)} & {tex(interval)} \\"
        )
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_threads(rows: list[dict[str, str]]) -> str:
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        (
            r"\caption{Thread scaling on 10000 frames of \texttt{cuh2.con}. "
            r"Speedup uses the 1-thread median. "
            r"Source: \texttt{paper/cpc/bench/results/threads\_summary.csv}.}"
        ),
        r"\label{tab:threads}",
        r"\begin{tabular}{rrrrl}",
        r"\toprule",
        r"Threads & Median (s) & Speedup & Efficiency & Field hash \\",
        r"\midrule",
    ]
    for row in rows:
        body.append(
            rf"{row['threads']} & {row['median_s']} & {row['speedup']} & "
            rf"{row['efficiency']} & {tex(row['hashes_identical_1_2_3_4_8'])} \\"
        )
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_cachegrind(rows: list[dict[str, str]]) -> str:
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        (
            r"\caption{Cachegrind instruction references for one whole-process "
            r"parse of the 1-frame payload. "
            r"Source: \texttt{paper/cpc/bench/results/cachegrind.csv}.}"
        ),
        r"\label{tab:cachegrind}",
        r"\begin{tabular}{lrr}",
        r"\toprule",
        r"Payload & I-refs & Status \\",
        r"\midrule",
    ]
    for row in rows:
        irefs = row["irefs"] or "0"
        body.append(
            rf"{tex(row['payload'])} & {int(irefs):,} & {tex(row['status'])} \\".replace(
                ",", r"\,"
            )
        )
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_loss(rows: list[dict[str, str]]) -> str:
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        r"\scriptsize",
        (
            r"\caption{Readers on the v3.1 rewrite of the public HCN/HNC endpoints. "
            r"Source: \texttt{paper/cpc/bench/results/hcn\_loss.csv}.}"
        ),
        r"\label{tab:loss}",
        r"\begin{tabular}{p{0.22\textwidth}p{0.16\textwidth}p{0.12\textwidth}p{0.40\textwidth}}",
        r"\toprule",
        r"Reader & File & Status & Record \\",
        r"\midrule",
    ]
    for row in rows:
        record = row["masks_xyz"] or row["detail"]
        if row["ids"]:
            record = f"masks {row['masks_xyz']}; ids {row['ids']}"
        body.append(
            rf"{tex(row['reader'])} & \texttt{{{tex(row['file'])}}} & "
            rf"{tex(row['status'])} & {tex(record)} \\"
        )
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_velocity(rows: list[dict[str, str]]) -> str:
    row = rows[0]
    lines = [
        ("readcon natural unit (fs)", row["readcon_natural_fs"]),
        ("canonical spelling", row["readcon_canonical"]),
        ("eOn timeUnit (fs)", row["eon_fs"]),
        ("relative difference", row["relative_fs"]),
        ("KE in the natural unit (eV)", row["ke_natural_eV"]),
        ("KE if those numbers are read as fs (eV)", row["ke_if_read_as_fs_eV"]),
        ("six-decimal relative KE loss", row["ke_relative_loss_6dp"]),
    ]
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        (
            r"\caption{Velocity unit check. The kinetic energies are the measurements "
            r"named in the specification. The factor is computed on this tree. "
            r"Source: \texttt{paper/cpc/bench/results/velocity\_case.csv}.}"
        ),
        r"\label{tab:velocity}",
        r"\begin{tabular}{lr}",
        r"\toprule",
        r"Quantity & Value \\",
        r"\midrule",
    ]
    for name, value in lines:
        body.append(rf"{tex(name)} & {tex(value)} \\")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_neb() -> str:
    import json

    text = NEB.read_text()
    frames = []
    role = ""
    for line in text.splitlines():
        if line.startswith("example NEB image"):
            match = re.search(r"\(([^)]+)\)", line)
            role = match.group(1) if match else "image"
        elif line.startswith("{"):
            meta = json.loads(line)
            frames.append(
                (
                    int(meta["neb_bead"]),
                    role,
                    float(meta["energy"]),
                    float(meta["fmax"]),
                )
            )
    if len(frames) != 4:
        raise SystemExit(f"neb_band.con expected 4 frames, got {len(frames)}")
    csv_path = DATA / "neb_band.csv"
    csv_path.write_text(
        "bead,role,energy_eV,fmax\n"
        + "\n".join(
            f"{bead},{role},{energy:.2f},{fmax:.2f}"
            for bead, role, energy, fmax in frames
        )
        + "\n"
    )
    barrier = frames[1][2] - frames[0][2]
    write("neb_macros.tex", rf"\newcommand{{\nebBarrierEv}}{{{barrier:.2f}}}" + "\n")
    body = [
        r"\begin{table}[ht]",
        r"\centering",
        (
            r"\caption{Declared bead metadata in \texttt{resources/examples/neb\_band.con}. "
            r"Source: \texttt{paper/cpc/data/neb\_band.csv}. "
            r"$E$ and $f_{\max}$ are line-2 JSON.}"
        ),
        r"\label{tab:neb}",
        r"\begin{tabular}{rllr}",
        r"\toprule",
        r"Bead & Role & $E$ (eV) & $f_{\max}$ \\",
        r"\midrule",
    ]
    for bead, role, energy, fmax in frames:
        body.append(rf"{bead} & {tex(role)} & {energy:.2f} & {fmax:.2f} \\")
    body += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    return "\n".join(body)


def gen_macros(
    clauses: list[dict[str, str]],
    phase: list[dict[str, str]],
    ratios: list[dict[str, str]],
) -> str:
    counts = {row["keyword"]: row["n"] for row in clauses}
    n_faster = sum(1 for row in ratios if row.get("readcon_faster") == "1")
    n_valid = sum(1 for row in phase if row["kind"] == "valid")
    n_invalid = sum(1 for row in phase if row["kind"] == "invalid")
    return "\n".join(
        [
            rf"\newcommand{{\nMust}}{{{counts.get('MUST', '0')}}}",
            rf"\newcommand{{\nMustNot}}{{{counts.get('MUST NOT', '0')}}}",
            rf"\newcommand{{\nShould}}{{{counts.get('SHOULD', '0')}}}",
            rf"\newcommand{{\nShouldNot}}{{{counts.get('SHOULD NOT', '0')}}}",
            rf"\newcommand{{\nMay}}{{{counts.get('MAY', '0')}}}",
            rf"\newcommand{{\nPhaseValid}}{{{n_valid}}}",
            rf"\newcommand{{\nPhaseInvalid}}{{{n_invalid}}}",
            rf"\newcommand{{\nHolmFaster}}{{{n_faster}}}",
            "",
        ]
    )


def main() -> None:
    for path in (
        RESULTS / "ratios.csv",
        RESULTS / "threads_summary.csv",
        RESULTS / "cachegrind.csv",
        RESULTS / "hcn_loss.csv",
        RESULTS / "velocity_case.csv",
        RESULTS / "faster_sentence.txt",
        DATA / "features.csv",
    ):
        require(path)
    clauses = clause_rows()
    phase = phase_rows()
    features = read_csv(DATA / "features.csv")
    ratios = read_csv(RESULTS / "ratios.csv")
    threads = read_csv(RESULTS / "threads_summary.csv")
    cachegrind = read_csv(RESULTS / "cachegrind.csv")
    loss = read_csv(RESULTS / "hcn_loss.csv")
    velocity = read_csv(RESULTS / "velocity_case.csv")
    write("macros.tex", gen_macros(clauses, phase, ratios))
    write("clause_table.tex", gen_clauses(clauses))
    write("phase_a_table.tex", gen_phase(phase))
    write("feature_table.tex", gen_features(features))
    write("ratio_table.tex", gen_ratios(ratios))
    write("thread_table.tex", gen_threads(threads))
    write("cachegrind_table.tex", gen_cachegrind(cachegrind))
    write("loss_table.tex", gen_loss(loss))
    write("velocity_table.tex", gen_velocity(velocity))
    write("neb_table.tex", gen_neb())
    sentence = (RESULTS / "faster_sentence.txt").read_text().strip()
    write("faster_sentence.tex", tex(sentence) + "\n")
    subprocess.check_call([sys.executable, str(CPC / "scripts" / "gen_figures.py")])
    print(f"wrote tables under {OUT}")


if __name__ == "__main__":
    main()
