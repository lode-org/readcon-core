def gen_io(ws: dict) -> str:
    par = ws["parallel"]
    return "\n".join(
        [
            r"\begin{table}[ht]",
            r"\centering",
            r"\caption{Median wall times, 100 frames of the 218-atom",
            r"\texttt{cuh2.con} geometry, five repeats",
            rf"(\texttt{{benches/results/wall\_scale.json}}, {ws['date_utc']}, host",
            rf"\texttt{{{ws['host']}}}, {ws['ncpus']} CPUs, tree \texttt{{{ws['commit']}}},",
            r"\texttt{cargo run --release --example wall\_scale\_harness",
            r"--features parallel}). Sequential is",
            r"\texttt{frames\_from\_text(..., Some(1))}. Auto is the $48$\,KiB",
            r"policy on the global Rayon pool. Pinned pools use",
            r"\texttt{parse\_frames\_parallel\_with\_threads}. Write is",
            r"\texttt{ConFrameWriter} into a memory buffer of those frames. Do",
            r"not average these with Table~\ref{tab:wall}.}",
            r"\label{tab:io}",
            r"\begin{tabular}{@{}llr@{}}",
            r"\toprule",
            r"Path & Policy & Median (ms) \\",
            r"\midrule",
            rf"Parse & sequential (\texttt{{n=1}}) & {_ms(ws['sequential_ms'])} \\",
            rf" & auto (global pool) & {_ms(ws['auto_ms'])} \\",
            rf" & Rayon $n=2$ & {_ms(par['n2'])} \\",
            rf" & Rayon $n=4$ & {_ms(par['n4'])} \\",
            rf" & Rayon $n=8$ & {_ms(par['n8'])} \\",
            rf" & Rayon $n=16$ & {_ms(par['n16'])} \\",
            r"\midrule",
            rf"Write & buffer, 100 frames & {_ms(ws['write_100_frames_ms'])} \\",
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ]
    )


def gen_neb() -> str:
    text = (ROOT / "resources/examples/neb_band.con").read_text()
    frames: list[tuple[int, str, float, float]] = []
    role = None
    for line in text.splitlines():
        if line.startswith("example NEB image"):
            m = re.search(r"\(([^)]+)\)", line)
            role = m.group(1) if m else "image"
        elif line.startswith("{"):
            meta = json.loads(line)
            frames.append(
                (
                    int(meta["neb_bead"]),
                    role or "image",
                    float(meta["energy"]),
                    float(meta["fmax"]),
                )
            )
    if len(frames) != 4:
        raise SystemExit(f"neb_band.con expected 4 frames, got {len(frames)}")
    rows = []
    for bead, role, e, fmax in frames:
        rows.append(rf"{bead} & {role} & ${e:.2f}$ & ${fmax:.2f}$ \\")
    e0 = frames[0][2]
    e1 = frames[1][2]
    barrier = e1 - e0
    _write(
        "neb_macros.tex",
        rf"\newcommand{{\nebBarrierEv}}{{{barrier:.2f}}}" + "\n",
    )
    return "\n".join(
        [
            r"\begin{table}[ht]",
            r"\centering",
            r"\caption{Declared NEB metadata recovered from",
            r"\texttt{resources/examples/neb\_band.con}. Spec~3, \texttt{units}",
            r"length=\texttt{angstrom}, energy=\texttt{eV},",
            r"\texttt{sections=[forces]}, \texttt{neb\_band=0}. $E$ and",
            r"$f_{\max}$ are line-2 JSON. They are not recomputed from the force",
            r"block.}",
            r"\label{tab:neb}",
            r"\begin{tabular}{@{}rlll@{}}",
            r"\toprule",
            r"Bead & Role & $E$ (eV) & $f_{\max}$ \\",
            r"\midrule",
            *rows,
            r"\bottomrule",
            r"\end{tabular}",
            r"\end{table}",
            "",
        ]
    )


def main() -> None:
    traj = _load(ROOT / "benches/results/ase_traj_vs_con.json")
    h5 = _load(ROOT / "benches/results/h5md_vs_con.json")
    cmp = _load(ROOT / "benches/results/compare_readers.json")
    ws = _load(ROOT / "benches/results/wall_scale.json")
    _write("macros.tex", gen_macros(traj, h5, ws, cmp))
    _write("cachegrind_table.tex", gen_cachegrind())
    _write("wall_table.tex", gen_wall(traj, h5, cmp))
    _write("io_table.tex", gen_io(ws))
    _write("neb_table.tex", gen_neb())
    print(f"wrote tables under {OUT}")


if __name__ == "__main__":
    main()
